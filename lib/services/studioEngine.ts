import {
  PaletteVariable,
  StudioComponentDefinition,
  SemanticStatusToken,
  INITIAL_SEMANTIC_STATUS_TOKENS,
} from '@/lib/data/studioData';

export function exportStudioToTokensJson(
  palette: PaletteVariable[],
  components: StudioComponentDefinition[],
  statusTokens: SemanticStatusToken[] = INITIAL_SEMANTIC_STATUS_TOKENS
): string {
  const result: any = {
    $schema: 'https://design-tokens.github.io/community-group/format/',
    name: 'AtomDesignToken System (Studio Generated)',
    version: '0.7.0',
    status: {},
    palette: {
      color: {},
      radius: {},
      spacing: {},
      status: {},
    },
    components: {},
  };

  // 1. Export Semantic Status Tokens
  statusTokens.forEach((st) => {
    result.status[st.key] = {
      $value: `{${st.paletteId}}`,
      $description: st.description,
      variable: st.id,
      hover: `{${st.hoverPaletteId}}`,
      subtle: `{${st.subtlePaletteId}}`,
    };
  });

  // 2. Export Palette
  palette.forEach((p) => {
    const key = p.id.replace(/^--atom-(palette-|radius-|space-|color-)/, '');
    if (!result.palette[p.category]) {
      result.palette[p.category] = {};
    }
    result.palette[p.category][key] = {
      $value: p.value,
      $type: p.category === 'color' || p.category === 'status' ? 'color' : 'dimension',
      $description: p.description || p.name,
      variable: p.id,
    };
  });

  // 3. Export Component Variables
  components.forEach((comp) => {
    result.components[comp.id] = {
      $description: comp.description,
      variables: {},
    };

    comp.variables.forEach((v) => {
      const bindingsObj: Record<string, any> = {};
      Object.entries(v.tokenBindings).forEach(([propKey, paletteId]) => {
        const matchedPalette = palette.find((p) => p.id === paletteId);
        bindingsObj[propKey] = {
          $value: `{${paletteId}}`,
          resolvedValue: matchedPalette?.value || '',
          targetVariable: paletteId,
        };
      });

      result.components[comp.id].variables[v.id] = {
        name: v.name,
        description: v.description || '',
        tokens: bindingsObj,
      };
    });
  });

  return JSON.stringify(result, null, 2);
}

export function exportStudioToCSS(
  palette: PaletteVariable[],
  components: StudioComponentDefinition[],
  statusTokens: SemanticStatusToken[] = INITIAL_SEMANTIC_STATUS_TOKENS
): string {
  let css = `/**\n * AtomDesignToken Studio Variables & Components CSS\n * Auto-generated by AtomDesignToken Studio\n */\n\n:root {\n  /* === 1. Global Palette Tokens === */\n`;

  // Palette variables
  palette.forEach((p) => {
    css += `  ${p.id}: ${p.value}; /* ${p.name} */\n`;
  });

  // 2. Semantic System State Tokens
  css += `\n  /* === 2. Semantic System State Tokens (상태 토큰) === */\n`;
  statusTokens.forEach((st) => {
    css += `  ${st.id}: var(${st.paletteId}); /* ${st.name} */\n`;
    if (st.hoverPaletteId) {
      css += `  ${st.id}-hover: var(${st.hoverPaletteId});\n`;
    }
    if (st.subtlePaletteId) {
      css += `  ${st.id}-subtle: var(${st.subtlePaletteId});\n`;
    }
  });

  // 3. Universal Semantic Aliases (Full system cascade)
  css += `\n  /* === 3. Universal Semantic Aliases (상태 토큰 전역 바인딩) === */\n`;
  css += `  --atom-primary: var(--atom-color-primary);\n`;
  css += `  --atom-primary-hover: var(--atom-color-primary-hover);\n`;
  css += `  --atom-primary-light: var(--atom-color-primary-subtle);\n`;
  css += `  --atom-secondary: var(--atom-color-secondary);\n`;
  css += `  --atom-secondary-hover: var(--atom-color-secondary-hover);\n`;
  css += `  --atom-secondary-light: var(--atom-color-secondary-subtle);\n`;
  css += `  --atom-success: var(--atom-color-success);\n`;
  css += `  --atom-success-hover: var(--atom-color-success-hover);\n`;
  css += `  --atom-success-light: var(--atom-color-success-subtle);\n`;
  css += `  --atom-destructive: var(--atom-color-danger);\n`;
  css += `  --atom-destructive-hover: var(--atom-color-danger-hover);\n`;
  css += `  --atom-destructive-light: var(--atom-color-danger-subtle);\n`;
  css += `  --atom-warning: var(--atom-color-warning);\n`;
  css += `  --atom-warning-hover: var(--atom-color-warning-hover);\n`;
  css += `  --atom-warning-light: var(--atom-color-warning-subtle);\n`;
  css += `  --atom-status-success: var(--atom-color-success);\n`;
  css += `  --atom-status-danger: var(--atom-color-danger);\n`;
  css += `  --atom-status-warning: var(--atom-color-warning);\n`;
  css += `  --accent-primary: var(--atom-color-primary);\n`;
  css += `  --accent-primary-hover: var(--atom-color-primary-hover);\n`;

  css += `}\n\n/* === 4. Component Variable Token Scopes & Direct Visual Selectors === */\n`;

  // Component Scoped CSS Variables & Direct Visual Selectors
  components.forEach((comp) => {
    comp.variables.forEach((v) => {
      // 1. Declare Scoped Token Variables
      css += `[data-component="${comp.id}"][data-variable="${v.id}"],\n.atom-${comp.id}--${v.id} {\n`;
      Object.entries(v.tokenBindings).forEach(([propKey, paletteId]) => {
        const cssVarName = `--atom-${comp.id}-${v.id}-${propKey}`;
        css += `  ${cssVarName}: var(${paletteId});\n`;
      });
      css += `}\n\n`;

      // 2. Concrete UI Component Selector Rules for 100% Direct Code Reflection
      if (comp.id === 'button') {
        css += `.atom-btn.atom-button--${v.id},\n.atom-btn[data-variable="${v.id}"],\n[data-component="button"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.textColor) css += `  color: var(--atom-${comp.id}-${v.id}-textColor);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.borderRadius) css += `  border-radius: var(--atom-${comp.id}-${v.id}-borderRadius);\n`;
        if (v.tokenBindings.paddingX || v.tokenBindings.paddingY) {
          const py = v.tokenBindings.paddingY ? `var(--atom-${comp.id}-${v.id}-paddingY)` : '8px';
          const px = v.tokenBindings.paddingX ? `var(--atom-${comp.id}-${v.id}-paddingX)` : '16px';
          css += `  padding: ${py} ${px};\n`;
        }
        css += `}\n`;
        if (v.tokenBindings.hoverBackground) {
          css += `.atom-btn.atom-button--${v.id}:hover:not(:disabled),\n.atom-btn[data-variable="${v.id}"]:hover:not(:disabled),\n[data-component="button"][data-variable="${v.id}"]:hover:not(:disabled) {\n`;
          css += `  background-color: var(--atom-${comp.id}-${v.id}-hoverBackground);\n`;
          css += `}\n\n`;
        }
      } else if (comp.id === 'badge') {
        css += `.atom-badge.atom-badge--${v.id},\n.atom-badge[data-variable="${v.id}"],\n[data-component="badge"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.textColor) css += `  color: var(--atom-${comp.id}-${v.id}-textColor);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.borderRadius) css += `  border-radius: var(--atom-${comp.id}-${v.id}-borderRadius);\n`;
        if (v.tokenBindings.paddingX || v.tokenBindings.paddingY) {
          const py = v.tokenBindings.paddingY ? `var(--atom-${comp.id}-${v.id}-paddingY)` : '2px';
          const px = v.tokenBindings.paddingX ? `var(--atom-${comp.id}-${v.id}-paddingX)` : '8px';
          css += `  padding: ${py} ${px};\n`;
        }
        css += `}\n\n`;
      } else if (comp.id === 'card') {
        css += `.atom-card.atom-card--${v.id},\n.atom-card[data-variable="${v.id}"],\n[data-component="card"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.borderRadius) css += `  border-radius: var(--atom-${comp.id}-${v.id}-borderRadius);\n`;
        if (v.tokenBindings.padding) css += `  padding: var(--atom-${comp.id}-${v.id}-padding);\n`;
        css += `}\n\n`;
      } else if (comp.id === 'input') {
        css += `.atom-input.atom-input--${v.id},\n.atom-input[data-variable="${v.id}"],\n[data-component="input"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.borderRadius) css += `  border-radius: var(--atom-${comp.id}-${v.id}-borderRadius);\n`;
        if (v.tokenBindings.textColor) css += `  color: var(--atom-${comp.id}-${v.id}-textColor);\n`;
        if (v.tokenBindings.paddingX || v.tokenBindings.paddingY) {
          const py = v.tokenBindings.paddingY ? `var(--atom-${comp.id}-${v.id}-paddingY)` : '8px';
          const px = v.tokenBindings.paddingX ? `var(--atom-${comp.id}-${v.id}-paddingX)` : '12px';
          css += `  padding: ${py} ${px};\n`;
        }
        css += `}\n`;
        if (v.tokenBindings.focusBorderColor) {
          css += `.atom-input.atom-input--${v.id}:focus,\n.atom-input[data-variable="${v.id}"]:focus,\n[data-component="input"][data-variable="${v.id}"]:focus {\n`;
          css += `  border-color: var(--atom-${comp.id}-${v.id}-focusBorderColor);\n`;
          css += `  outline: 2px solid var(--atom-${comp.id}-${v.id}-focusBorderColor);\n`;
          css += `}\n\n`;
        }
      } else if (comp.id === 'navbar') {
        css += `.atom-navbar.atom-navbar--${v.id},\n.atom-navbar[data-variable="${v.id}"],\n[data-component="navbar"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.borderRadius) css += `  border-radius: var(--atom-${comp.id}-${v.id}-borderRadius);\n`;
        if (v.tokenBindings.textColor) css += `  color: var(--atom-${comp.id}-${v.id}-textColor);\n`;
        css += `}\n\n`;
      } else if (comp.id === 'sidebar') {
        css += `.atom-sidebar.atom-sidebar--${v.id},\n.atom-sidebar[data-variable="${v.id}"],\n[data-component="sidebar"][data-variable="${v.id}"] {\n`;
        if (v.tokenBindings.background) css += `  background-color: var(--atom-${comp.id}-${v.id}-background);\n`;
        if (v.tokenBindings.borderColor) css += `  border-color: var(--atom-${comp.id}-${v.id}-borderColor);\n`;
        if (v.tokenBindings.textColor) css += `  color: var(--atom-${comp.id}-${v.id}-textColor);\n`;
        css += `}\n`;
        if (v.tokenBindings.activeBackground || v.tokenBindings.activeText) {
          css += `.atom-sidebar.atom-sidebar--${v.id} [aria-current="page"],\n.atom-sidebar[data-variable="${v.id}"] [aria-current="page"] {\n`;
          if (v.tokenBindings.activeBackground) css += `  background-color: var(--atom-${comp.id}-${v.id}-activeBackground);\n`;
          if (v.tokenBindings.activeText) css += `  color: var(--atom-${comp.id}-${v.id}-activeText);\n`;
          css += `}\n\n`;
        }
      }
    });
  });

  return css;
}
