import { PaletteVariable, StudioComponentDefinition } from '@/lib/data/studioData';

export function exportStudioToTokensJson(
  palette: PaletteVariable[],
  components: StudioComponentDefinition[]
): string {
  const result: any = {
    $schema: 'https://design-tokens.github.io/community-group/format/',
    name: 'AtomDesignToken System (Studio Generated)',
    version: '0.6.1',
    palette: {
      color: {},
      radius: {},
      spacing: {},
    },
    components: {},
  };

  // 1. Export Palette
  palette.forEach((p) => {
    const key = p.id.replace(/^--atom-(palette-|radius-|space-)/, '');
    result.palette[p.category][key] = {
      $value: p.value,
      $type: p.category === 'color' ? 'color' : 'dimension',
      $description: p.description || p.name,
      variable: p.id,
    };
  });

  // 2. Export Component Variables
  components.forEach((comp) => {
    result.components[comp.id] = {
      $description: comp.description,
      variables: {},
    };

    comp.variables.forEach((v) => {
      const bindingsObj: Record<string, any> = {};
      Object.entries(v.tokenBindings).forEach(([propKey, paletteId]) => {
        const matchedPalette = palette.find((p) => p.id === paletteId);
        bindingsObj[propKey] = {
          $value: `{${paletteId}}`,
          resolvedValue: matchedPalette?.value || '',
          targetVariable: paletteId,
        };
      });

      result.components[comp.id].variables[v.id] = {
        name: v.name,
        description: v.description || '',
        tokens: bindingsObj,
      };
    });
  });

  return JSON.stringify(result, null, 2);
}

export function exportStudioToCSS(
  palette: PaletteVariable[],
  components: StudioComponentDefinition[]
): string {
  let css = `/**\n * AtomDesignToken Studio Variables & Components CSS\n * Auto-generated by AtomDesignToken Studio\n */\n\n:root {\n  /* === 1. Global Palette Tokens === */\n`;

  // Palette variables
  palette.forEach((p) => {
    css += `  ${p.id}: ${p.value}; /* ${p.name} */\n`;
  });

  css += `}\n\n/* === 2. Component Variable Token Scopes === */\n`;

  // Component Scoped CSS Variables
  components.forEach((comp) => {
    comp.variables.forEach((v) => {
      css += `[data-component="${comp.id}"][data-variable="${v.id}"],\n.atom-${comp.id}--${v.id} {\n`;
      Object.entries(v.tokenBindings).forEach(([propKey, paletteId]) => {
        const cssVarName = `--atom-${comp.id}-${v.id}-${propKey}`;
        css += `  ${cssVarName}: var(${paletteId});\n`;
      });
      css += `}\n\n`;
    });
  });

  return css;
}
